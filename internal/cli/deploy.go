func (o *options) presetCommand() *cobra.Command {
	command := &cobra.Command{Use: "preset", Aliases: []string{"presets"}, Short: "Browse the dashboard preset catalog"}
	command.AddCommand(&cobra.Command{Use: "list", Aliases: []string{"ls"}, Short: "List available service presets", Args: validateArguments,
		RunE: func(command *cobra.Command, _ []string) error {
			catalog, err := presets.Fetch(command.Context(), o.catalogURL)
			if err != nil {
				return err
			}
			type entry struct {
				ID          string `json:"id"`
				Name        string `json:"name"`
				Description string `json:"description"`
				Image       string `json:"image"`
			}
			entries := make([]entry, 0, len(catalog.Presets))
			for _, preset := range catalog.Presets {
				entries = append(entries, entry{preset.Settings.PresetID, preset.Name, preset.Description, preset.Settings.Image})
			}
			sort.Slice(entries, func(i, j int) bool { return entries[i].ID < entries[j].ID })
			rows := [][]string{{"ID", "NAME", "DESCRIPTION"}}
			for _, preset := range entries {
				rows = append(rows, []string{preset.ID, preset.Name, preset.Description})
			}
			return o.print(command, entries, rows)
		},
	})
	return command
}

func (o *options) deployCommand() *cobra.Command {
	var serverName, name string
	var environment []string
	command := &cobra.Command{
		Use: "deploy <preset>", Short: "Create a service from a preset (requires a read-write token)", Args: validateArguments,
		Long:    "Create a new service from the same presets as the dashboard. Run 'sliplane preset list' for IDs.\nChoose an existing project and server with flags, or interactively when there are multiple choices.\nGenerated names and credentials are fresh for each deployment. Creation starts deployment; it does not wait for readiness.",
		Example: "  sliplane deploy n8n\n  sliplane deploy n8n --project production --server main --name workflows",
		RunE: func(command *cobra.Command, args []string) error {
			if strings.TrimSpace(args[0]) == "" {
				return errors.New("preset must not be empty")
			}
			for flag, value := range map[string]string{"name": name, "server": serverName, "project": o.project} {
				if command.Flags().Changed(flag) && strings.TrimSpace(value) == "" {
					return fmt.Errorf("--%s must not be empty", flag)
				}
			}
			overrides, err := deploymentEnvironment(environment)
			if err != nil {
				return err
			}
			client, _, err := o.client(command)
			if err != nil {
				return err
			}
			catalog, err := presets.Fetch(command.Context(), o.catalogURL)
			if err != nil {
				return err
			}
			preset, err := catalog.Instantiate(args[0])
			if err != nil {
				return err
			}
			input, err := presetServiceInput(preset, overrides)
			if err != nil {
				return err
			}
			if name != "" {
				input.Name = name
			}
			project, server, err := o.deploymentDestination(command, client, serverName)
			if err != nil {
				return err
			}
			input.ServerID = server.id
			if !command.Flags().Changed("name") && o.canPrompt(command) {
				field := huh.NewInput().Title("Service name").Value(&input.Name).Validate(func(value string) error {
					if strings.TrimSpace(value) == "" {
						return errors.New("service name must not be empty")
					}
					return nil
				})
				if err := runPrompt(command, field); err != nil {
					return fmt.Errorf("enter service name: %w", err)
				}
			}
			service, err := client.CreateService(command.Context(), project.id, input)
			if err != nil {
				return err
			}
			return o.printCreatedService(command, service, args[0], project, server)
		},
	}
	command.Flags().StringVar(&serverName, "server", "", "Existing server name or ID")
	command.Flags().StringVar(&name, "name", "", "Service name (prompts interactively; default: generated by the preset)")
	command.Flags().StringArrayVar(&environment, "env", nil, "Override a preset environment variable: KEY=value, or KEY to read from your environment (repeatable; stored as secret)")
	return command
}

func deploymentEnvironment(values []string) ([]api.EnvironmentVariable, error) {
	entries := []api.EnvironmentVariable{}
	for _, value := range values {
		entry, err := parseEnvironmentVariable(value)
		if err != nil {
			return nil, err
		}
		if entry.Value == "" {
			return nil, fmt.Errorf("environment variable %q is empty; supply --env KEY=value or set it locally", entry.Key)
		}
		entries = append(entries, entry)
	}
	return entries, nil
}

// parseEnvironmentVariable accepts literal values or local variables without echoing values on errors.
func parseEnvironmentVariable(value string) (api.EnvironmentVariable, error) {
	key, content, supplied := strings.Cut(value, "=")
	if strings.TrimSpace(key) == "" || strings.ContainsAny(key, " \t\r\n\x00") {
		return api.EnvironmentVariable{}, errors.New("environment variables require KEY=value or KEY")
	}
	if !supplied {
		var exists bool
		content, exists = os.LookupEnv(key)
		if !exists {
			return api.EnvironmentVariable{}, fmt.Errorf("environment variable %q is not set locally; supply KEY=value or set it locally", key)
		}
	}
	return api.EnvironmentVariable{Key: key, Value: content, Secret: true}, nil
}

// presetServiceInput translates dashboard fields to the public creation API without silently losing mounts.
func presetServiceInput(preset presets.Preset, overrides []api.EnvironmentVariable) (api.CreateServiceInput, error) {
	settings := preset.Settings
	if settings.DeploySource != "registry" || settings.Image == "" || settings.Name == "" {
		return api.CreateServiceInput{}, fmt.Errorf("preset %q has unsupported or incomplete image configuration", settings.PresetID)
	}
	if settings.Public && settings.Protocol != "http" && settings.Protocol != "tcp" && settings.Protocol != "udp" {
		return api.CreateServiceInput{}, fmt.Errorf("preset %q has an invalid network protocol", settings.PresetID)
	}
	input := api.CreateServiceInput{Name: settings.Name, Deployment: api.ServiceDeployment{URL: settings.Image}, Network: api.ServiceNetwork{Public: settings.Public, Protocol: settings.Protocol}, Cmd: settings.Cmd}
	if settings.Protocol == "http" {
		input.Healthcheck = settings.Healthcheck
	}
	input.Env = append([]api.EnvironmentVariable{}, settings.Env...)
	for _, override := range overrides {
		found := false
		for index := range input.Env {
			if input.Env[index].Key == override.Key {
				input.Env[index] = override
				found = true
				break
			}
		}
		if !found {
			input.Env = append(input.Env, override)
		}
	}
	for _, entry := range input.Env {
		if entry.Key == "" || entry.Value == "" {
			return api.CreateServiceInput{}, fmt.Errorf("preset %q requires a value for %q; supply --env KEY=value or --env KEY", settings.PresetID, entry.Key)
		}
	}
	for _, mount := range settings.Volumes {
		volumeName := ""
		for _, volume := range preset.Volumes {
			if volume.ID == mount.ID {
				volumeName = volume.Name
				break
			}
		}
		if volumeName == "" || !strings.HasPrefix(mount.Path, "/") {
			return api.CreateServiceInput{}, fmt.Errorf("preset %q has an invalid volume mount", settings.PresetID)
		}
		input.Volumes = append(input.Volumes, api.ServiceVolume{Name: volumeName, MountPath: mount.Path})
	}
	return input, nil
}

func (o *options) deploymentDestination(command *cobra.Command, client *api.Client, serverName string) (choice, choice, error) {
	projects, err := client.Projects(command.Context())
	if err != nil {
		return choice{}, choice{}, err
	}
	projectChoices := make([]choice, len(projects))
	for index, project := range projects {
		projectChoices[index] = choice{project.ID, project.Name}
	}
	project, err := o.chooseDeploymentResource(command, "project", o.project, projectChoices)
	if err != nil {
		return choice{}, choice{}, err
	}
	servers, err := client.Servers(command.Context())
	if err != nil {
		return choice{}, choice{}, err
	}
	serverChoices := make([]choice, len(servers))
	for index, server := range servers {
		serverChoices[index] = choice{server.ID, server.Name}
	}
	server, err := o.chooseDeploymentResource(command, "server", serverName, serverChoices)
	return project, server, err
}

func (o *options) chooseDeploymentResource(command *cobra.Command, kind, query string, choices []choice) (choice, error) {
	if query != "" {
		index, err := resolve(kind, query, choices)
		if err != nil {
			return choice{}, err
		}
		return choices[index], nil
	}
	if len(choices) == 0 {
		return choice{}, fmt.Errorf("no %ss available; create one before deploying", kind)
	}
	if len(choices) == 1 {
		return choices[0], nil
	}
	if !o.canPrompt(command) {
		return choice{}, fmt.Errorf("multiple %ss available; specify --%s NAME or ID", kind, kind)
	}
	sorted := append([]choice{}, choices...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].name < sorted[j].name })
	entries := make([]huh.Option[choice], 0, len(sorted))
	for _, candidate := range sorted {
		label := fmt.Sprintf("%s (%s)", terminalText(candidate.name), terminalText(candidate.id))
		entries = append(entries, huh.NewOption(label, candidate))
	}
	var selected choice
	field := huh.NewSelect[choice]().Title("Choose " + kind).Options(entries...).Height(10).Value(&selected)
	if err := runPrompt(command, field); err != nil {
		return choice{}, fmt.Errorf("choose %s: %w", kind, err)
	}
	return selected, nil
}

// printCreatedService emits a creation receipt without returning environment credentials.
func (o *options) printCreatedService(command *cobra.Command, service api.Service, presetID string, project, server choice) error {
	receipt := struct {
		ID         string          `json:"id"`
		Name       string          `json:"name"`
		Status     string          `json:"status"`
		Preset     string          `json:"preset,omitempty"`
		ProjectID  string          `json:"projectId"`
		ServerID   string          `json:"serverId"`
		URL        string          `json:"url,omitempty"`
		Deployment json.RawMessage `json:"deployment,omitempty"`
		Network    json.RawMessage `json:"network,omitempty"`
	}{ID: service.ID, Name: service.Name, Status: service.Status, Preset: presetID, ProjectID: project.id, ServerID: server.id, Deployment: service.Deployment, Network: service.Network}
	var network api.ServiceNetworkDetails
	if err := json.Unmarshal(service.Network, &network); err == nil && network.Public && network.Protocol == "http" && network.ManagedDomain != "" {
		receipt.URL = "https://" + network.ManagedDomain
	}
	rows := [][]string{{"Created", service.Name}, {"ID", service.ID}}
	if presetID != "" {
		rows = append(rows, []string{"Preset", presetID})
	}
	rows = append(rows, []string{"Project", project.name}, []string{"Server", server.name})
	details, err := serviceDetailRows(service)
	if err != nil {
		return err
	}
	rows = append(rows, details...)
	rows = append(rows, []string{"Status", service.Status})
	return o.print(command, receipt, rows)
}
